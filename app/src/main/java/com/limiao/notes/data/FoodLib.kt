    val CATEGORIES: List<String> = listOf("主食", "肉蛋", "蛋奶豆", "蔬菜", "水果", "饮品", "零食", "家常菜", "调味")

    /** 按名称模糊匹配；关键词为空则返回全部。命中的越靠前越优先（完全等于 > 开头 > 包含） */
    fun search(keyword: String): List<FoodItem> {
        val k = keyword.trim()
        if (k.isEmpty()) return ALL
        val hit = ALL.filter { it.name.contains(k, ignoreCase = true) }
        return hit.sortedWith(
            compareBy(
                { if (it.name == k) 0 else 1 },
                { if (it.name.startsWith(k)) 0 else 1 },
                { it.name.length },
            )
        )
    }

    fun byCategory(cat: String): List<FoodItem> = ALL.filter { it.cat == cat }

    fun find(name: String): FoodItem? = ALL.firstOrNull { it.name == name }

    /** 按克数换算出一条记录的热量与三大营养素 */
    fun calc(item: FoodItem, grams: Double): Calc {
        if (grams <= 0) return Calc(0.0, 0.0, 0.0, 0.0)
        val f = grams / 100.0
        return Calc(item.kcal * f, item.carbs * f, item.protein * f, item.fat * f)
    }

    data class Calc(val kcal: Double, val carbs: Double, val protein: Double, val fat: Double)

